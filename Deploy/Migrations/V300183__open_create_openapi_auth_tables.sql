-- 3. 调用审计：open.open_api_invoke_log（只增不改，无 gmt_update / 无更新触发器）
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS open.open_api_invoke_log (
    idn             BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    client_idn      BIGINT        NOT NULL DEFAULT 0,
    credential_idn  BIGINT        NOT NULL DEFAULT 0,
