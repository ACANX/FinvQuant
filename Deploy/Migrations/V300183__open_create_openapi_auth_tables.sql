-- ---------------------------------------------------------------------
-- 2. 凭证：open.open_api_credential
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS open.open_api_credential (
    idn                BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    client_idn         BIGINT        NOT NULL,
    credential_no      VARCHAR(48)   NOT NULL,
    auth_mode          VARCHAR(16)   NOT NULL,
    access_key_id      VARCHAR(64)   NOT NULL,
    key_prefix         VARCHAR(12)   NULL,
    secret_hash        VARCHAR(128)  NULL,
    secret_cipher      TEXT          NULL,
    secret_cipher_prev TEXT          NULL,
    dt_secret_rotate   TIMESTAMPTZ   NULL,
    secret_kid         VARCHAR(16)   NULL,
    sign_algorithm     VARCHAR(16)   NOT NULL DEFAULT 'HMAC-SHA256',
    scope_str          JSONB         NOT NULL DEFAULT '[]'::jsonb,
    allow_cidr         CIDR[]        NOT NULL DEFAULT '{}',
    dt_expire          TIMESTAMPTZ   NULL,
    dt_last_use        TIMESTAMPTZ   NULL,
    count_use          BIGINT        NOT NULL DEFAULT 0,
    flag_enable        CHAR(1)       NOT NULL DEFAULT '1',
    flag_revoke        CHAR(1)       NOT NULL DEFAULT '0',
    dt_revoke          TIMESTAMPTZ   NULL,
    reason_revoke      VARCHAR(500)  NULL,
    remark             VARCHAR(2000) NULL,
    create_by          VARCHAR(32)   NULL,
    modify_by          VARCHAR(32)   NULL,
    gmt_create         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    gmt_update         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT pk_open_api_credential PRIMARY KEY (idn),
    CONSTRAINT uk_open_api_credential_no UNIQUE (credential_no),
    CONSTRAINT uk_open_api_credential_access_key UNIQUE (access_key_id),
    CONSTRAINT ck_open_api_credential_mode
        CHECK (auth_mode IN ('API_KEY','AK_SK','BEARER','MTLS','BASIC')),
    CONSTRAINT ck_open_api_credential_secret
        CHECK ( (auth_mode =  'AK_SK' AND secret_cipher IS NOT NULL AND secret_hash IS NULL)
             OR (auth_mode <> 'AK_SK' AND secret_hash   IS NOT NULL) ),
    CONSTRAINT ck_open_api_credential_sign_algorithm
        CHECK (sign_algorithm IN ('HMAC-SHA256','HMAC-SHA512','ED25519')),
    CONSTRAINT ck_open_api_credential_flag_enable CHECK (flag_enable IN ('0','1')),
    CONSTRAINT ck_open_api_credential_flag_revoke CHECK (flag_revoke IN ('0','1')),
    CONSTRAINT ck_open_api_credential_revoke_trace
        CHECK (flag_revoke = '0' OR (dt_revoke IS NOT NULL AND NULLIF(btrim(reason_revoke), '') IS NOT NULL)),
    CONSTRAINT ck_open_api_credential_count_use CHECK (count_use >= 0),
    CONSTRAINT ck_open_api_credential_scope_is_array
        CHECK (jsonb_typeof(scope_str) = 'array')
);

COMMENT ON TABLE  open.open_api_credential IS '外部 OpenAPI 凭证：一行 = 一种认证模式的凭证（API_KEY / AK_SK / BEARER / MTLS / BASIC）';
COMMENT ON COLUMN open.open_api_credential.idn IS '主键，自增';
COMMENT ON COLUMN open.open_api_credential.client_idn IS '所属调用方（对 open.open_api_client.idn，程序层校验，无物理外键）';
COMMENT ON COLUMN open.open_api_credential.credential_no IS '凭证号（唯一，人工识别用，如 cred-cdeu-01）';
COMMENT ON COLUMN open.open_api_credential.auth_mode IS '认证模式：API_KEY 静态密钥 / AK_SK 签名 / BEARER JWT / MTLS 双向证书 / BASIC 用户名口令';
COMMENT ON COLUMN open.open_api_credential.access_key_id IS '公开标识（唯一）：API_KEY 模式为 key 本身（fk_live_xxx）；AK_SK 模式为 AK；MTLS 模式为证书指纹';
COMMENT ON COLUMN open.open_api_credential.key_prefix IS '密钥前 8 位明文，列表页展示与检索用（绝不回显全量密钥）';
COMMENT ON COLUMN open.open_api_credential.secret_hash IS '密钥哈希（不可逆）：API_KEY 模式为 sha256、BASIC 模式为 argon2id PHC 串；AK_SK 模式必须为 NULL';
COMMENT ON COLUMN open.open_api_credential.secret_cipher IS 'SK 密文（AES-256-GCM，密钥取 sys_config 19005、KID 取 19004）：HMAC 验签需取回明文，故只能加密不能哈希；非 AK_SK 模式必须为 NULL';
COMMENT ON COLUMN open.open_api_credential.secret_cipher_prev IS '轮换期的旧 SK 密文（双密钥并行，无感换钥）；过了并行窗口置空';
COMMENT ON COLUMN open.open_api_credential.dt_secret_rotate IS '最近一次密钥轮换时间';
COMMENT ON COLUMN open.open_api_credential.secret_kid IS '加密密钥版本（对应 sys_config 19004），换密钥后仍能解密历史密文';
COMMENT ON COLUMN open.open_api_credential.sign_algorithm IS '签名算法（默认 HMAC-SHA256，预留 HMAC-SHA512 / ED25519）';
COMMENT ON COLUMN open.open_api_credential.scope_str IS '授权范围（jsonb 数组，元素形如 {"method":"POST","path":"/OpenAPI/V1/Meta/Finv/Quote/Cdeu/Min/Upsert"}；空数组 = 该路由组全部接口）；后续可扩展为 open.open_api_credential_scope 表';
COMMENT ON COLUMN open.open_api_credential.allow_cidr IS '凭证级 IP 白名单（空数组 = 不限），与调用方级白名单取交集';
COMMENT ON COLUMN open.open_api_credential.dt_expire IS '凭证过期时间（NULL = 随调用方）';
COMMENT ON COLUMN open.open_api_credential.dt_last_use IS '最近一次认证成功时间（异步节流回写，可能略滞后）';
COMMENT ON COLUMN open.open_api_credential.count_use IS '累计认证成功次数（异步累加，可能略滞后）';
COMMENT ON COLUMN open.open_api_credential.flag_enable IS '启用标志：0 停用 / 1 启用';
COMMENT ON COLUMN open.open_api_credential.flag_revoke IS '吊销标志：0 正常 / 1 已吊销（吊销后不可再启用，只能新建凭证）';
COMMENT ON COLUMN open.open_api_credential.dt_revoke IS '吊销时间（flag_revoke=1 时必填）';
COMMENT ON COLUMN open.open_api_credential.reason_revoke IS '吊销原因（flag_revoke=1 时必填）';
COMMENT ON COLUMN open.open_api_credential.remark IS '备注';
COMMENT ON COLUMN open.open_api_credential.create_by IS '创建人';
COMMENT ON COLUMN open.open_api_credential.modify_by IS '最后修改人';
COMMENT ON COLUMN open.open_api_credential.gmt_create IS '创建时间';
COMMENT ON COLUMN open.open_api_credential.gmt_update IS '更新时间（触发器 open.tf_open_api_set_gmt_update 维护）';

CREATE INDEX IF NOT EXISTS idx_open_api_credential_client
    ON open.open_api_credential (client_idn);

-- 鉴权热路径只扫「启用且未吊销」的行
