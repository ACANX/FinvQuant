     '兼容期兜底静态密钥：鉴权启用后，携带该密钥的请求仍按旧口径放行（等价环境变量 FINV_OPENAPI_KEY，二者任一命中即可）。用于尚未改造的旧调用方过渡；留空表示不启用兜底。敏感信息，请勿在日志/前端明文回显')
ON CONFLICT (config_no) DO NOTHING;

-- ---------------------------------------------------------------------
-- 5. 收敛校验（只断言本脚本自己刚写的结构）
-- ---------------------------------------------------------------------
DO $$
DECLARE
    v_missing TEXT;
    v_fk      INT;
    v_trg     INT;
    v_cfg     INT;
    v_chk     INT;
    v_cred    INT;
    v_log     INT;
BEGIN
    -- 5.1 三张表存在
    SELECT string_agg(t, ', ') INTO v_missing
      FROM unnest(ARRAY['open.open_api_client','open.open_api_credential','open.open_api_invoke_log']) AS t
     WHERE to_regclass(t) IS NULL;
    IF v_missing IS NOT NULL THEN
        RAISE EXCEPTION 'V300183 校验失败：表未创建（%）', v_missing;
    END IF;

    -- 5.2 关键列存在且类型正确（按「缺哪列报哪列」，避免断言列数被后续加列打破）
    WITH want(tbl, col, typ) AS (VALUES
        ('open_api_client','idn','bigint'),
        ('open_api_client','client_code','character varying'),
        ('open_api_client','allow_cidr','ARRAY'),
        ('open_api_client','flag_enable','character'),
        ('open_api_client','gmt_create','timestamp with time zone'),
        ('open_api_client','gmt_update','timestamp with time zone'),
        ('open_api_credential','client_idn','bigint'),
        ('open_api_credential','auth_mode','character varying'),
        ('open_api_credential','access_key_id','character varying'),
        ('open_api_credential','secret_hash','character varying'),
        ('open_api_credential','secret_cipher','text'),
        ('open_api_credential','secret_cipher_prev','text'),
        ('open_api_credential','secret_kid','character varying'),
        ('open_api_credential','scope_str','jsonb'),
        ('open_api_credential','flag_revoke','character'),
        ('open_api_credential','dt_revoke','timestamp with time zone'),
        ('open_api_credential','reason_revoke','character varying'),
        ('open_api_credential','gmt_update','timestamp with time zone'),
        ('open_api_invoke_log','dt_request','timestamp with time zone'),
        ('open_api_invoke_log','flag_pass','character'),
        ('open_api_invoke_log','reason_code','character varying'),
        ('open_api_invoke_log','body_sha256','character'),
        ('open_api_invoke_log','ip','inet')
    )
    SELECT string_agg(w.tbl || '.' || w.col, ', ') INTO v_missing
      FROM want w
      LEFT JOIN information_schema.columns c
             ON c.table_schema = 'open' AND c.table_name = w.tbl AND c.column_name = w.col
     WHERE c.column_name IS NULL OR c.data_type <> w.typ;
    IF v_missing IS NOT NULL THEN
        RAISE EXCEPTION 'V300183 校验失败：列缺失或类型不符（%）', v_missing;
    END IF;

    -- 5.3 全库 0 物理外键（DbSchemaSpec 基本要求）
    SELECT count(*) INTO v_fk
      FROM pg_constraint c
      JOIN pg_class t ON t.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = t.relnamespace
     WHERE c.contype = 'f' AND n.nspname = 'open';
    IF v_fk <> 0 THEN
        RAISE EXCEPTION 'V300183 校验失败：open schema 出现 % 个物理外键（要求 0）', v_fk;
    END IF;

    -- 5.4 关键约束存在（认证模式枚举 / 密钥二选一 / 吊销留痕 / scope 为数组 / 两条唯一键）
    SELECT count(*) INTO v_chk
      FROM pg_constraint c
      JOIN pg_class t ON t.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = t.relnamespace
     WHERE n.nspname = 'open'
       AND c.conname IN ('ck_open_api_credential_mode','ck_open_api_credential_secret',
                         'ck_open_api_credential_revoke_trace','ck_open_api_credential_scope_is_array',
                         'uk_open_api_credential_access_key','uk_open_api_credential_no');
    IF v_chk <> 6 THEN
        RAISE EXCEPTION 'V300183 校验失败：凭证表应有 6 个关键约束，实际 %', v_chk;
    END IF;

    -- 5.5 两个 gmt_update 触发器存在（日志表刻意不建）
    SELECT count(*) INTO v_trg
      FROM pg_trigger tg
      JOIN pg_class t ON t.oid = tg.tgrelid
      JOIN pg_namespace n ON n.oid = t.relnamespace
     WHERE n.nspname = 'open' AND NOT tg.tgisinternal
       AND tg.tgname IN ('trg_open_api_client_set_gmt_update','trg_open_api_credential_set_gmt_update');
    IF v_trg <> 2 THEN
        RAISE EXCEPTION 'V300183 校验失败：应有 2 个 gmt_update 触发器，实际 %', v_trg;
    END IF;

    -- 5.6 系统配置 19001～19006 齐全且 data_type 正确
    SELECT count(*) INTO v_cfg FROM sys.sys_config
     WHERE (config_no = 19001 AND data_type = '2')
        OR (config_no = 19002 AND data_type = '1')
        OR (config_no = 19003 AND data_type = '1')
        OR (config_no IN (19004, 19005, 19006) AND data_type = '3');
    IF v_cfg <> 6 THEN
        RAISE EXCEPTION 'V300183 校验失败：sys_config 19001～19006 应齐全且 data_type 正确，实际匹配 % 条', v_cfg;
    END IF;

    -- 5.7 数据质量信息：只报告不阻断（凭证由运维在「OpenAPI 调用方管理」里录入）
    SELECT count(*) INTO v_cred FROM open.open_api_credential;
    SELECT count(*) INTO v_log  FROM open.open_api_invoke_log;
    RAISE NOTICE 'V300183 就绪：调用方 % 个、凭证 % 条、调用日志 % 条；鉴权模式 19001=%（0 关闭 / 1 启用 / 2 宽松）',
        (SELECT count(*) FROM open.open_api_client), v_cred, v_log,
        (SELECT char_value FROM sys.sys_config WHERE config_no = 19001);
    IF v_cred = 0 THEN
        RAISE NOTICE 'V300183 提示：尚无凭证；鉴权启用前必须先录入凭证，否则所有 OpenAPI 请求都会被拒（19001=0 时不受影响）';
    END IF;
END $$;

COMMIT;
