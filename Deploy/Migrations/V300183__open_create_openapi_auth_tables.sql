    dt_request      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    method          VARCHAR(8)    NULL,
    path            VARCHAR(512)  NULL,
    query_str       VARCHAR(2000) NULL,
    status_code     INTEGER       NOT NULL DEFAULT 0,
    biz_code        INTEGER       NOT NULL DEFAULT 0,
    flag_pass       CHAR(1)       NOT NULL DEFAULT '0',
    reason_code     VARCHAR(32)   NULL,
    ip              INET          NULL,
    user_agent      VARCHAR(512)  NULL,
    body_sha256     CHAR(64)      NULL,
    count_body      INTEGER       NOT NULL DEFAULT 0,
    latency_ms      INTEGER       NOT NULL DEFAULT 0,
    gmt_create      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT pk_open_api_invoke_log PRIMARY KEY (idn),
    CONSTRAINT ck_open_api_invoke_log_flag_pass CHECK (flag_pass IN ('0','1')),
    CONSTRAINT ck_open_api_invoke_log_status_code CHECK (status_code >= 0),
    CONSTRAINT ck_open_api_invoke_log_count_body CHECK (count_body >= 0),
    CONSTRAINT ck_open_api_invoke_log_latency_ms CHECK (latency_ms >= 0)
);

