-- =====================================================================
-- FinvQuant PostgreSQL V300183：外部 OpenAPI 鉴权表（open schema，3 张）+ 系统配置 19001～19006
--
-- 需求：11167（建表）；11168（鉴权中间件，另行实现）；11169（「OpenAPI 调用方管理」菜单，另行实现）
-- 授权依据：用户在 2026-11-15 会话中逐条确定以下设计，本迁移即其固化：
--   ① schema 用 `open`，表名一律以 `open_` 开头；
--   ② 系统配置用 19xxx 号段（本迁移占 19001～19006）；错误码用 190xx 子段（登记在 ErrorCodeSpec）；
--   ③ 时间列：创建/修改统一 `gmt_create` / `gmt_update`，其它按需 `gmt_` 或 `dt_`；
--   ④ SK 加密密钥来源 `sys.sys_config`（19004 存 KID、19005 存密钥本体，不预填）；
--   ⑤ 防重放 nonce 存 Redis（**不建 nonce 表**）；
--   ⑥ 授权范围 `scope_str` 先用 jsonb 单列，后续可扩展为 `open.open_api_credential_scope`；
--   ⑦ 兼容期保留环境变量 `FINV_OPENAPI_KEY` 兜底，并由 19001 开关支持「系统临时关闭鉴权」。
--
-- 建了什么：
--   1. open.open_api_client      调用方（一行 = 一个接入应用）
--   2. open.open_api_credential  凭证（一行 = 一种认证模式的凭证；API_KEY / AK_SK / BEARER / MTLS / BASIC）
--   3. open.open_api_invoke_log    调用审计（只增不改；表名用户定稿为 invoke_log，既有库由 V300184 改名）
--   4. 触发器 open_api_client / open_api_credential 的 gmt_update 自动维护
--   5. sys.sys_config 19001～19006（鉴权模式开关 / 签名时间窗 / 日志保留天数 / 密钥 KID / 密钥本体 / 兼容兜底密钥）
--
-- 关键约束（不得随意放宽）：
--   - 全库 **0 物理外键**（DbSchemaSpec「跨域引用只走程序层」）：client_idn 等关联列不建 FK；
--   - 静态 Key 存**哈希**（`secret_hash`）；AK/SK 模式必须能取回明文做 HMAC → 存**密文**（`secret_cipher`），
--     两者按 `auth_mode` 用 CHECK 约束二选一，杜绝「明文密钥落库」与「该能解密却没有密钥」两种错；
--   - 吊销必须留原因与时间（`flag_revoke='1'` → `dt_revoke` / `reason_revoke` 非空，CHECK 强约束）；
--   - 调用日志**只存请求体摘要与长度**（`body_sha256` / `count_body`），不存原文（行情明细含业务数据）；
--   - 【红线】种子不得覆盖用户后来改过的值：`sys_config` 一律 `ON CONFLICT (config_no) DO NOTHING`，本文件无 DO UPDATE。
--
-- 幂等：CREATE SCHEMA/TABLE/INDEX IF NOT EXISTS、COMMENT 可重复执行、
--   触发器先 DROP IF EXISTS 再建、种子 ON CONFLICT DO NOTHING；重跑影响 0 行。
-- 迁移策略：单事务（BEGIN/COMMIT），失败整体回滚。
-- 收敛校验口径：只断言**本脚本自己刚写的结构**（表/列/约束/索引/触发器/配置行存在性与类型）；
--   行数、凭证明细等数据质量信息一律 `RAISE NOTICE`，不阻断迁移。
-- 前置：schema open（V100013）、public.vq_set_gmt_update()（V200001 起）、sys.sys_config（V200072）。
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 0. schema 兜底（V100013 已建；此处保证单独执行本文件也不失败）
-- ---------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS open AUTHORIZATION CURRENT_USER;

-- ---------------------------------------------------------------------
-- 1. 调用方：open.open_api_client
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS open.open_api_client (
    idn             BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    client_code     VARCHAR(32)   NOT NULL,
    client_name     VARCHAR(128)  NOT NULL,
    owner_uid       VARCHAR(32)   NULL,
    contact_email   VARCHAR(128)  NULL,
    contract_no     VARCHAR(64)   NULL,
    allow_cidr      CIDR[]        NOT NULL DEFAULT '{}',
    rate_limit_rpm  INTEGER       NOT NULL DEFAULT 0,
    quota_day       INTEGER       NOT NULL DEFAULT 0,
    dt_expire       TIMESTAMPTZ   NULL,
    flag_enable     CHAR(1)       NOT NULL DEFAULT '0',
    remark          VARCHAR(2000) NULL,
    create_by       VARCHAR(32)   NULL,
    modify_by       VARCHAR(32)   NULL,
    gmt_create      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    gmt_update      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT pk_open_api_client PRIMARY KEY (idn),
    CONSTRAINT uk_open_api_client_code UNIQUE (client_code),
    CONSTRAINT ck_open_api_client_flag_enable CHECK (flag_enable IN ('0','1')),
    CONSTRAINT ck_open_api_client_rate_limit_rpm CHECK (rate_limit_rpm >= 0),
    CONSTRAINT ck_open_api_client_quota_day CHECK (quota_day >= 0)
);

COMMENT ON TABLE  open.open_api_client IS '外部 OpenAPI 调用方：一行 = 一个接入应用（可持有多条凭证，可同时用多种认证模式）';
COMMENT ON COLUMN open.open_api_client.idn IS '主键，自增';
COMMENT ON COLUMN open.open_api_client.client_code IS '调用方代号（唯一，人工识别用，如 cdeu-hook）';
COMMENT ON COLUMN open.open_api_client.client_name IS '调用方名称（如「CDEU 采集钩子」）';
COMMENT ON COLUMN open.open_api_client.owner_uid IS '负责人账号（对 sys.sys_user.uid，程序层校验，无物理外键）';
COMMENT ON COLUMN open.open_api_client.contact_email IS '联系邮箱';
COMMENT ON COLUMN open.open_api_client.contract_no IS '合同/授权编号，审计追溯用';
COMMENT ON COLUMN open.open_api_client.allow_cidr IS '调用方级 IP 白名单（空数组 = 不限）；判定用 cidr <<= 运算；与凭证级白名单取交集';
COMMENT ON COLUMN open.open_api_client.rate_limit_rpm IS '每分钟调用上限（0 = 不限），计数存 Redis';
COMMENT ON COLUMN open.open_api_client.quota_day IS '每日调用配额（0 = 不限），计数存 Redis';
COMMENT ON COLUMN open.open_api_client.dt_expire IS '授权到期时间（NULL = 长期）';
COMMENT ON COLUMN open.open_api_client.flag_enable IS '启用标志：0 停用 / 1 启用（新建默认停用，核对后手工开）';
COMMENT ON COLUMN open.open_api_client.remark IS '备注';
COMMENT ON COLUMN open.open_api_client.create_by IS '创建人';
COMMENT ON COLUMN open.open_api_client.modify_by IS '最后修改人';
COMMENT ON COLUMN open.open_api_client.gmt_create IS '创建时间';
COMMENT ON COLUMN open.open_api_client.gmt_update IS '更新时间（触发器 open.tf_open_api_set_gmt_update 维护）';

CREATE INDEX IF NOT EXISTS idx_open_api_client_enable
    ON open.open_api_client (flag_enable) WHERE flag_enable = '1';

