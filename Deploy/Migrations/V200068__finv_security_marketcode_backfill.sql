-- FinvQuant PostgreSQL V200068：回填 finv_security.market_code 并启用历史种子证券
--
-- 背景（用户实测）：
--   V200002（15 条）/ V200009（503 条）两批证券种子插入时 finv_security 尚无
--   market_code 列（该列由 V100019 以 DEFAULT 0 补加），导致这两批共 470 条
--   证券的 market_code 长期停留在 0（「待维护」），无法参与按市场的行情导入、
--   归档导出与去重取数；同时它们因 flag_enable='0' 一直处于禁用状态。
--
-- 取值依据（不编造，逐条可追溯）：
--   1. 其中 400 条能按 usc 关联到 futu.finv_futu_quote_collect（V100083/V200063），
--      直接套用 V200062 生成时使用的同一份转换口径
--      （FinvQuantDesign/Scripts/SecuSync/SecuMapping.json 的 marketCodeByFutu，
--      即 富途 market_code → finv_market.market_code）；
--   2. 余下 70 条无富途采集记录（历史自造 usc，如 SHI / HS300I / N225 / LIST0309），
--      按「exchange_code + security_type + 代码形态」推导，并按以下人工决策落库：
--      · 上交所指数/债券指数/基金指数 → 1110；深交所指数 → 1120；北交所指数 → 1130；
--      · 港股指数 → 1201；香港期货（含 100000 黄金期货）→ 1250（HKFE-F）；
--      · 新加坡证券/指数 → 1511；日本（GLDMain / N225）→ 1501；
--      · 板块 Sector（LIST*）→ 8000（板块/行业分类）；
--      · 美股宽基股（BRK.B / EA / MTBLY）→ 1312；美股指数（DAJI→1314 归入 1312、
--        SDPR500→1310）；CBOE 的 VXMain → 1318；
--      · exchange_code=100 兜底桶：KOSPI→1508、SENSEX→1521、USDindex→1253、
--        CN10Y/US10Y/USPRL→2003、0828EA/LU0788108826→3001、HK0000311842→2001、
--        LIST22881→8000；
--      · 曾按配置落到 finv_market 不存在的 1150 的 9 条香港期货，统一改到 1250；
--      · 曾落到 finv_market 不存在的 1313 的 11 条中概 ADR，统一改到 1331（US-OTC）。
--   3. 原 market_code=1314（配置侧存在、finv_market 未登记的重复码）的 180 条美股
--      指数按语义细分：道琼斯美国行业指数（DJUSxx）→ 1311（美股行业指数）、
--      道琼斯宽基/风格 → 1312（美股指数-道琼斯系列）、
--      标普/纳指/Wilshire/Cboe/波动率 → 1310（美股指数）。
--
-- 幂等策略：
--   · 清单先入临时表，UPDATE 一律带 `market_code IS DISTINCT FROM 目标值`；
--     已按本脚本改过的库上重跑，影响 0 行；
--   · 启用语句只动 flag_enable='0' 且 usc 在清单内的行，重跑影响 0 行；
--   · 末尾做收敛校验：清单内 470 条必须 market_code 正确且 flag_enable='1'，
--     原 1314 的 180 条必须market_code 正确，否则整事务回滚。
-- 迁移策略：单事务（BEGIN/COMMIT），失败整体回滚。
-- 前置：V100019（market_code 列）、V100018（flag_enable 列）、V200062（富途批次）。
