-- V200060：BRS（Backup & Restore Service）备份登记表与每日备份配置
--
-- 需求 10800：
--   · 新增 brs schema；
--   · brs.brs_bak_rdb_table 登记需要备份的表（priority 唯一，越大越先）；
--   · sys.sys_config 39001 保存每日备份 cron（6 段：秒 分 时 日 月 周）；
--   · 预置系统表与 CDEU 配置表种子（不含 cdeu.finv_quote_secu_kline_min）。
-- =====================================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS brs;

CREATE TABLE IF NOT EXISTS brs.brs_bak_rdb_table (
    idn            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 主键
    rdb_type       varchar(32)  NOT NULL DEFAULT 'postgresql',                -- 数据库类型（首期 postgresql）
    schema_name    varchar(64)  NOT NULL,                                     -- schema 名（避开保留字 schema）
    table_name     varchar(128) NOT NULL,                                     -- 表名
    flag_enable    char(1)      NOT NULL DEFAULT '1',                         -- 备份开关：1 启用 / 0 停用
    priority       integer      NOT NULL,                                     -- 执行优先级，越大越先（值唯一）
    bak_scope      varchar(16)  NOT NULL DEFAULT 'both',                      -- 备份范围：both / schema / data
    bak_method     varchar(16)  NOT NULL DEFAULT 'pg_dump',                   -- 备份方式：首期 pg_dump
    compression    varchar(16)  NOT NULL DEFAULT 'zstd',                      -- 压缩：none / gzip / zstd
    where_clause   text,                                                      -- 预留：部分数据备份条件
    remark         text,                                                      -- 备注
    creator        varchar(32),                                               -- 创建人（sys_user.uid）
    gmt_create     timestamptz  NOT NULL DEFAULT now(),                       -- 创建时间
    gmt_update     timestamptz  NOT NULL DEFAULT now(),                       -- 修改时间（触发器维护）
    CONSTRAINT uq_brs_bak_rdb_table UNIQUE (rdb_type, schema_name, table_name), -- 同一库内表唯一
    CONSTRAINT uq_brs_bak_rdb_table_priority UNIQUE (priority),                 -- 优先级值唯一
    CONSTRAINT ck_brs_bak_rdb_table_flag CHECK (flag_enable IN ('0', '1')),     -- 开关取值
    CONSTRAINT ck_brs_bak_rdb_table_priority CHECK (priority >= 0),             -- 优先级非负
    CONSTRAINT ck_brs_bak_rdb_table_scope CHECK (bak_scope IN ('both', 'schema', 'data')), -- 范围取值
    CONSTRAINT ck_brs_bak_rdb_table_method CHECK (bak_method IN ('pg_dump', 'copy')),      -- 方式取值
    CONSTRAINT ck_brs_bak_rdb_table_compression CHECK (compression IN ('none', 'gzip', 'zstd')) -- 压缩取值
);

COMMENT ON TABLE brs.brs_bak_rdb_table IS '需要备份的 RDB 表登记（BRS）';
COMMENT ON COLUMN brs.brs_bak_rdb_table.idn IS '主键';
COMMENT ON COLUMN brs.brs_bak_rdb_table.rdb_type IS '数据库类型（首期 postgresql）';
COMMENT ON COLUMN brs.brs_bak_rdb_table.schema_name IS 'schema 名';
COMMENT ON COLUMN brs.brs_bak_rdb_table.table_name IS '表名';
COMMENT ON COLUMN brs.brs_bak_rdb_table.flag_enable IS '备份开关：1 启用 / 0 停用';
COMMENT ON COLUMN brs.brs_bak_rdb_table.priority IS '执行优先级，越大越先（值唯一）';
COMMENT ON COLUMN brs.brs_bak_rdb_table.bak_scope IS '备份范围：both/schema/data';
COMMENT ON COLUMN brs.brs_bak_rdb_table.bak_method IS '备份方式：pg_dump/copy';
COMMENT ON COLUMN brs.brs_bak_rdb_table.compression IS '压缩：none/gzip/zstd';
COMMENT ON COLUMN brs.brs_bak_rdb_table.where_clause IS '预留：部分数据备份条件（首期 pg_dump 不生效）';
COMMENT ON COLUMN brs.brs_bak_rdb_table.remark IS '备注';
COMMENT ON COLUMN brs.brs_bak_rdb_table.creator IS '创建人（sys_user.uid）';
COMMENT ON COLUMN brs.brs_bak_rdb_table.gmt_create IS '创建时间';
COMMENT ON COLUMN brs.brs_bak_rdb_table.gmt_update IS '修改时间（触发器维护）';

CREATE OR REPLACE FUNCTION brs.brs_set_gmt_update()
RETURNS TRIGGER AS $$
BEGIN
    NEW.gmt_update := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_brs_bak_rdb_table_gmt_update ON brs.brs_bak_rdb_table;
CREATE TRIGGER trg_brs_bak_rdb_table_gmt_update
    BEFORE UPDATE ON brs.brs_bak_rdb_table
    FOR EACH ROW EXECUTE FUNCTION brs.brs_set_gmt_update();

