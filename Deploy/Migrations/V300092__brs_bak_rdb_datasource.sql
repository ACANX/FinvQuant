-- =====================================================================
-- V300092：BRS RDB 数据源登记表 brs.brs_bak_rdb_datasource
--
-- 需求 10909：先把「备份目标数据源」的登记表建好，业务功能（连接测试、
--   按数据源执行备份、口令加解密、页面维护）后续需求再实现。
--
-- 为什么需要：当前备份链路的连接参数只来自环境变量（FINV_PG_*），
--   只能备份当前实例这一个库；多个实例/跨库备份需要把数据源落库管理。
--
-- 首期约定（业务未实现前仅为占位与后续扩展）：
--   · 不插种子数据（当前实例仍走 FINV_PG_* 环境变量）；
--   · password_cipher 预留：后续由部署侧写入加密口令；为空时回退环境变量口令；
--   · code 供业务登记表引用（`brs_bak_rdb_table_full.db` / `_incr.db` 的取值来源）。
-- =====================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS brs.brs_bak_rdb_datasource (
    idn             bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- 主键
    code            varchar(64)  NOT NULL,                                     -- 数据源编码（唯一，供备份登记引用）
    name            varchar(128) NOT NULL,                                     -- 显示名称
    rdb_type        varchar(32)  NOT NULL DEFAULT 'postgresql',                -- 数据库类型（首期 postgresql）
    host            varchar(255) NOT NULL,                                     -- 主机名或 IP
    port            integer      NOT NULL DEFAULT 5432,                        -- 端口
    database_name   varchar(128) NOT NULL,                                     -- 数据库名
    username        varchar(128) NOT NULL,                                     -- 连接用户
    password_cipher text,                                                      -- 连接口令（加密后文本；为空时回退环境变量）
    ssl_mode        varchar(16)  NOT NULL DEFAULT 'prefer',                    -- SSL 模式
    connect_timeout integer      NOT NULL DEFAULT 10,                          -- 连接超时（秒）
    is_default      char(1)      NOT NULL DEFAULT '0',                         -- 是否默认数据源：1 是 / 0 否（全表最多一条 1）
    flag_enable     char(1)      NOT NULL DEFAULT '1',                         -- 启用开关：1 启用 / 0 停用
    priority        integer      NOT NULL DEFAULT 100,                         -- 多数据源时的选用顺序，越大越先
    remark          text,                                                      -- 备注
    creator         varchar(32),                                               -- 创建人（sys_user.uid）
    gmt_create      timestamptz  NOT NULL DEFAULT now(),                       -- 创建时间
    gmt_update      timestamptz  NOT NULL DEFAULT now(),                       -- 修改时间（触发器维护）
    CONSTRAINT uq_brs_bak_rdb_datasource_code UNIQUE (code),
    CONSTRAINT uq_brs_bak_rdb_datasource_name UNIQUE (name),
    CONSTRAINT ck_brs_bak_rdb_datasource_rdb_type CHECK (rdb_type IN ('postgresql')),
    CONSTRAINT ck_brs_bak_rdb_datasource_port CHECK (port BETWEEN 1 AND 65535),
    CONSTRAINT ck_brs_bak_rdb_datasource_ssl CHECK (ssl_mode IN ('disable', 'allow', 'prefer', 'require', 'verify-ca', 'verify-full')),
    CONSTRAINT ck_brs_bak_rdb_datasource_timeout CHECK (connect_timeout BETWEEN 1 AND 600),
    CONSTRAINT ck_brs_bak_rdb_datasource_flags CHECK (is_default IN ('0', '1') AND flag_enable IN ('0', '1')),
    CONSTRAINT ck_brs_bak_rdb_datasource_priority CHECK (priority >= 0)
);

-- 默认数据源全表最多一条（部分唯一索引）
CREATE UNIQUE INDEX IF NOT EXISTS uq_brs_bak_rdb_datasource_default
    ON brs.brs_bak_rdb_datasource ((is_default))
 WHERE is_default = '1';

COMMENT ON TABLE brs.brs_bak_rdb_datasource IS
    'BRS RDB 备份数据源登记（首期仅建表，连接测试与按数据源备份待后续需求实现）';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.idn IS '主键';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.code IS '数据源编码（唯一，供备份登记引用）';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.name IS '显示名称';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.rdb_type IS '数据库类型（首期 postgresql）';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.host IS '主机名或 IP';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.port IS '端口（1~65535）';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.database_name IS '数据库名';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.username IS '连接用户';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.password_cipher IS
    '连接口令（加密后文本）；为空时回退环境变量 FINV_PG_PASSWORD。加密方式与密钥管理待后续需求确定，不得明文写入';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.ssl_mode IS 'SSL 模式：disable/allow/prefer/require/verify-ca/verify-full';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.connect_timeout IS '连接超时（秒，1~600）';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.is_default IS '是否默认数据源：1 是 / 0 否（全表最多一条 1）';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.flag_enable IS '启用开关：1 启用 / 0 停用';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.priority IS '多数据源选用顺序，越大越先';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.remark IS '备注';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.creator IS '创建人（sys_user.uid）';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.gmt_create IS '创建时间';
COMMENT ON COLUMN brs.brs_bak_rdb_datasource.gmt_update IS '修改时间（触发器维护）';

-- gmt_update 触发器复用 V300060 已建函数 brs.brs_set_gmt_update()
DROP TRIGGER IF EXISTS trg_brs_bak_rdb_datasource_gmt_update ON brs.brs_bak_rdb_datasource;
CREATE TRIGGER trg_brs_bak_rdb_datasource_gmt_update
    BEFORE UPDATE ON brs.brs_bak_rdb_datasource
    FOR EACH ROW EXECUTE FUNCTION brs.brs_set_gmt_update();

COMMIT;
