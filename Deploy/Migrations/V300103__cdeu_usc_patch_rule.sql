-- =====================================================================
-- V300103：USC 补丁规则表（需求 10931）
--
-- 背景：
--   cdeu.finv_quote_secu_kline_min 里会持续出现 SH000688、KC50 这类过时 usc 的行情，
--   上游采集口径短期不会同步，重新导入时旧代码会再次写回。一次性迁移解决不了，
--   需要「规则表 + 定期执行」的机制，方案见 Docs/Proposal/202611-0002。
--
-- 本迁移只建规则表与初始规则，不执行任何数据迁移。
-- =====================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS cdeu.finv_quote_cdeu_usc_patch_rule (
    idn         bigint      GENERATED BY DEFAULT AS IDENTITY,
    usc_old     text        NOT NULL,
    usc_new     text        NOT NULL,
    match_mode  text        NOT NULL DEFAULT 'exact',
    flag_enable char(1)     NOT NULL DEFAULT '1',
    priority    integer     NOT NULL DEFAULT 100,
    note        text        NOT NULL DEFAULT '',
    gmt_create  timestamptz NOT NULL DEFAULT now(),
    gmt_update  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT finv_quote_cdeu_usc_patch_rule_pkey PRIMARY KEY (idn),
    CONSTRAINT ck_finv_quote_cdeu_usc_patch_rule_not_self CHECK (usc_old <> usc_new),
    CONSTRAINT ck_finv_quote_cdeu_usc_patch_rule_match_mode CHECK (match_mode IN ('exact', 'prefix')),
    CONSTRAINT ck_finv_quote_cdeu_usc_patch_rule_flag_enable CHECK (flag_enable IN ('0', '1')),
    CONSTRAINT ck_finv_quote_cdeu_usc_patch_rule_priority CHECK (priority >= 0),
    CONSTRAINT ck_finv_quote_cdeu_usc_patch_rule_usc_not_blank CHECK (btrim(usc_old) <> '' AND btrim(usc_new) <> '')
);

-- 同一个过时 usc 同时只能有一条生效规则，否则迁移方向不确定。
CREATE UNIQUE INDEX IF NOT EXISTS uq_finv_quote_cdeu_usc_patch_rule_usc_old
    ON cdeu.finv_quote_cdeu_usc_patch_rule (usc_old)
 WHERE flag_enable = '1';

CREATE INDEX IF NOT EXISTS idx_finv_quote_cdeu_usc_patch_rule_new
    ON cdeu.finv_quote_cdeu_usc_patch_rule (usc_new);

COMMENT ON TABLE cdeu.finv_quote_cdeu_usc_patch_rule IS 'USC 补丁规则：把过时 usc 的行情按规则迁移到新 usc，支持动态维护与定期执行';
COMMENT ON COLUMN cdeu.finv_quote_cdeu_usc_patch_rule.idn IS '规则序号，自增主键';
COMMENT ON COLUMN cdeu.finv_quote_cdeu_usc_patch_rule.usc_old IS '过时 usc（将被替换），如 SH000688';
COMMENT ON COLUMN cdeu.finv_quote_cdeu_usc_patch_rule.usc_new IS '目标 usc（替换为），如 SH0688；不能与 usc_old 相同';
COMMENT ON COLUMN cdeu.finv_quote_cdeu_usc_patch_rule.match_mode IS '匹配方式：exact 精确匹配、prefix 前缀匹配（首版只启用 exact）';
COMMENT ON COLUMN cdeu.finv_quote_cdeu_usc_patch_rule.flag_enable IS '是否生效：1 生效、0 停用；停用不删除，便于追溯';
COMMENT ON COLUMN cdeu.finv_quote_cdeu_usc_patch_rule.priority IS '优先级，数值小的先匹配；同一 usc_old 同时只允许一条生效规则';
COMMENT ON COLUMN cdeu.finv_quote_cdeu_usc_patch_rule.note IS '规则依据与来源说明，如需求编号或评审结论';
COMMENT ON COLUMN cdeu.finv_quote_cdeu_usc_patch_rule.gmt_create IS '创建时间';
COMMENT ON COLUMN cdeu.finv_quote_cdeu_usc_patch_rule.gmt_update IS '更新时间（触发器自动维护）';

DROP TRIGGER IF EXISTS trg_finv_quote_cdeu_usc_patch_rule_gmt_update ON cdeu.finv_quote_cdeu_usc_patch_rule;
CREATE TRIGGER trg_finv_quote_cdeu_usc_patch_rule_gmt_update
    BEFORE UPDATE ON cdeu.finv_quote_cdeu_usc_patch_rule
    FOR EACH ROW EXECUTE FUNCTION vq_set_gmt_update();

