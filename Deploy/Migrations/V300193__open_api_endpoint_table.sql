-- =====================================================================
-- FinvQuant PostgreSQL V300193：open schema 新增 open.open_api_endpoint（对外接口清单）
--
-- 需求：11220（建表 + 登记既有 4 个可调接口）。
-- 授权依据：用户在 2026-11-11 会话中明确确认四项设计并批准落地：
--   ① 表名 open.open_api_endpoint；
--   ② api_code 用「点分小写」（如 cdeu.min.pageuni）；
--   ③ path 含 `/OpenAPI/V1` 前缀（与 open_api_credential_scope.path_pattern、审计表 path 同口径）；
--   ④ 本轮只建表 + 种子，不改读写代码（与 V300192 的节奏一致）。
--
-- 定位（**必须守住**）：
--   本表是「接口目录 + 元数据」，**不是**鉴权白名单。
--   允许调哪些接口由代码里的路由注册决定（`internal/api/router.go` 的 openGroup）；
--   本表只用来：给授权范围页面做下拉、给审计报表提供稳定锚点（api_code）、
--   标注读/写（静态 Key 的 `_` 时间戳约束）与是否对外公开。
--   若哪天把本表当成「允许清单」去拦截请求，一旦漏登记就会出现幽灵接口，禁止这样做。
--
-- 关键点：
--   - `api_code` 是稳定业务编码：**路径将来重命名时它不变**，审计/套餐/限额靠它锚定；
--   - `UNIQUE (http_method, path)` 保证同一路由只有一行；`api_code` 与小写点分格式由 CHECK 收敛；
--   - `flag_write` 标记写接口（静态 Key 调写接口必须带查询参数 `_`，需求 11188）；
--   - 下线接口用 `dt_deprecate` 留痕，不物理删除（审计里可能还引用）；
--   - 全库 **0 物理外键**（DbSchemaSpec「跨域引用只走程序层」）；
--   - 种子一律 `ON CONFLICT DO NOTHING`——【红线】不得覆盖用户后来改过的中文名/开关。
--
-- 幂等：CREATE TABLE/INDEX IF NOT EXISTS、COMMENT 可重复、触发器先 DROP IF EXISTS 再建、
--   种子 ON CONFLICT DO NOTHING；重跑影响 0 行。
-- 迁移策略：单事务（BEGIN/COMMIT），失败整体回滚。
-- 收敛校验口径：只断言**本脚本自己刚写的结构**（表/列/约束/触发器存在性 + 4 条种子可查到）；
--   代码注册路由数与表行数的比对只 `RAISE NOTICE`（代码可能条件注册，不阻断迁移）。
-- 前置：schema open（V100013）、public.vq_set_gmt_update()（V200001）。
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 0. schema 兜底（V100013 已建；此处保证单独执行本文件也不失败）
-- ---------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS open AUTHORIZATION CURRENT_USER;

-- ---------------------------------------------------------------------
-- 1. 接口清单：open.open_api_endpoint
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS open.open_api_endpoint (
    idn            BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    api_code       VARCHAR(48)  NOT NULL,
    http_method    VARCHAR(8)   NOT NULL,
    path           VARCHAR(256) NOT NULL,
    api_name       VARCHAR(128) NOT NULL,
    api_group      VARCHAR(64)  NULL,
    flag_write     CHAR(1)      NOT NULL DEFAULT '0',
    flag_public    CHAR(1)      NOT NULL DEFAULT '1',
    flag_enable    CHAR(1)      NOT NULL DEFAULT '1',
    dt_deprecate   TIMESTAMPTZ  NULL,
    remark         VARCHAR(500) NULL,
    create_by      VARCHAR(32)  NULL,
    modify_by      VARCHAR(32)  NULL,
    gmt_create     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    gmt_update     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_open_api_endpoint PRIMARY KEY (idn),
    CONSTRAINT uk_open_api_endpoint_code UNIQUE (api_code),
    CONSTRAINT uk_open_api_endpoint_route UNIQUE (http_method, path),
    CONSTRAINT ck_open_api_endpoint_code
        CHECK (api_code ~ '^[a-z][a-z0-9]*(\.[a-z0-9]+)+$'),
    CONSTRAINT ck_open_api_endpoint_method
        CHECK (http_method IN ('GET','POST','PUT','PATCH','DELETE','HEAD','OPTIONS')),
    CONSTRAINT ck_open_api_endpoint_path
        CHECK (path LIKE '/OpenAPI/V1/%'),
    CONSTRAINT ck_open_api_endpoint_flag_write  CHECK (flag_write  IN ('0','1')),
    CONSTRAINT ck_open_api_endpoint_flag_public CHECK (flag_public IN ('0','1')),
    CONSTRAINT ck_open_api_endpoint_flag_enable CHECK (flag_enable IN ('0','1'))
);

COMMENT ON TABLE  open.open_api_endpoint IS
    '对外 OpenAPI 接口清单（目录 + 元数据，**不是**鉴权白名单；允许调什么由代码路由决定）（需求 11220）';
COMMENT ON COLUMN open.open_api_endpoint.idn IS '主键，自增';
COMMENT ON COLUMN open.open_api_endpoint.api_code IS
    '稳定业务编码（点分小写，如 cdeu.min.pageuni）：路径重命名时不变，审计报表/套餐/限额用它锚定';
COMMENT ON COLUMN open.open_api_endpoint.http_method IS 'HTTP 方法（只登记真实方法，不含 *；* 只出现在授权范围的通配规则里）';
COMMENT ON COLUMN open.open_api_endpoint.path IS
    '完整路径，含 /OpenAPI/V1 前缀（与 open_api_credential_scope.path_pattern、open_api_invoke_log.path 同口径）';
COMMENT ON COLUMN open.open_api_endpoint.api_name IS '中文名（页面下拉与报表展示用）';
COMMENT ON COLUMN open.open_api_endpoint.api_group IS '分组（分钟行情 / 实时行情 / 鉴权 …），页面按此归类';
COMMENT ON COLUMN open.open_api_endpoint.flag_write IS
    '是否写接口：1 = 写（静态 Key 调用时必须带查询参数 `_` 毫秒时间戳，需求 11188），0 = 读';
COMMENT ON COLUMN open.open_api_endpoint.flag_public IS '是否对外公开：1 = 是（可出现在授权范围下拉里），0 = 内部保留';
COMMENT ON COLUMN open.open_api_endpoint.flag_enable IS '启用标志：0 停用（不再推荐授权）/ 1 启用；停用不影响既有授权调用';
COMMENT ON COLUMN open.open_api_endpoint.dt_deprecate IS '下线时间（NULL = 在服务；不物理删除，审计可能还引用）';
COMMENT ON COLUMN open.open_api_endpoint.remark IS '备注（注册位置、特殊限制等）';
COMMENT ON COLUMN open.open_api_endpoint.create_by IS '创建人（种子行为 migrate）';
COMMENT ON COLUMN open.open_api_endpoint.modify_by IS '最后修改人';
COMMENT ON COLUMN open.open_api_endpoint.gmt_create IS '创建时间';
COMMENT ON COLUMN open.open_api_endpoint.gmt_update IS
    '更新时间（触发器 trg_open_api_endpoint_set_gmt_update 维护）';

DROP TRIGGER IF EXISTS trg_open_api_endpoint_set_gmt_update ON open.open_api_endpoint;
CREATE TRIGGER trg_open_api_endpoint_set_gmt_update
    BEFORE UPDATE ON open.open_api_endpoint
    FOR EACH ROW EXECUTE FUNCTION public.vq_set_gmt_update();

-- ---------------------------------------------------------------------
-- 2. 种子：登记既有 4 个可调接口
--
-- 与 internal/api/router.go 的 openGroup 逐条对应：
--   openGroup.POST("/Meta/Finv/Quote/Cdeu/Min/Upsert")                → cdeu.min.upsert
--   openGroup.GET ("/Meta/Finv/Quote/Cdeu/Min/PageUni")               → cdeu.min.pageuni
--   openGroup.POST("/Meta/Auth/Credential/STS/Issue")                 → auth.sts.issue
--   openGroup.POST("/Meta/Finv/Quote/Cdeu/Realtime/FTStockUpsert")    → cdeu.realtime.stockupsert
--     （最后一条仅在 deps.ExportArchive != nil 时注册；本表照常登记，是否可调由路由决定）
--
-- 3 条 DELETE 占位路由（11180）是「显式拒绝删除」，不是可调接口，不登记。
-- 【红线】ON CONFLICT DO NOTHING：绝不覆盖用户后来改过的中文名/开关。
-- ---------------------------------------------------------------------
INSERT INTO open.open_api_endpoint
    (api_code, http_method, path, api_name, api_group, flag_write, flag_public, flag_enable,
     remark, create_by)
VALUES
    ('cdeu.min.pageuni', 'GET', '/OpenAPI/V1/Meta/Finv/Quote/Cdeu/Min/PageUni',
     '分钟行情分页查询', '分钟行情', '0', '1', '1',
     'router.go openGroup.GET；读接口，静态 Key 可直接调用', 'migrate'),
    ('cdeu.min.upsert', 'POST', '/OpenAPI/V1/Meta/Finv/Quote/Cdeu/Min/Upsert',
     '分钟行情批量写入', '分钟行情', '1', '1', '1',
     'router.go openGroup.POST；写接口，静态 Key 调用必须带查询参数 `_`（毫秒时间戳，±60 秒）', 'migrate'),
    ('cdeu.realtime.stockupsert', 'POST', '/OpenAPI/V1/Meta/Finv/Quote/Cdeu/Realtime/FTStockUpsert',
     '实时行情快照写入', '实时行情', '1', '1', '1',
     'router.go openGroup.POST（deps.ExportArchive 非空时注册）；写接口', 'migrate'),
    ('auth.sts.issue', 'POST', '/OpenAPI/V1/Meta/Auth/Credential/STS/Issue',
     'STS 临时凭据换证', '鉴权', '0', '1', '1',
     'router.go openGroup.POST；只有 STS 兑换凭证（token_fp 为空）可调，AKSK 与临时凭据调用一律 403/19009（需求 11210）', 'migrate')
ON CONFLICT DO NOTHING;

-- ---------------------------------------------------------------------
-- 3. 收敛校验（只断言结构性事实；路由数与表行数的比对只输出提示）
-- ---------------------------------------------------------------------
DO $$
DECLARE
    v_cols   INT;
    v_pk     INT;
    v_uk     INT;
    v_chk    INT;
    v_trg    INT;
    v_seed   INT;
    v_rows   BIGINT;
BEGIN
    -- 3.1 表与列（15 列）
    SELECT count(*) INTO v_cols FROM information_schema.columns
     WHERE table_schema = 'open' AND table_name = 'open_api_endpoint';
    IF v_cols <> 15 THEN
        RAISE EXCEPTION 'V300193 校验失败：open_api_endpoint 列数应为 15，实际 %', v_cols;
    END IF;

    -- 3.2 主键
    SELECT count(*) INTO v_pk FROM pg_constraint c
      JOIN pg_class r ON r.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = r.relnamespace
     WHERE n.nspname = 'open' AND r.relname = 'open_api_endpoint' AND c.contype = 'p';
    IF v_pk <> 1 THEN
        RAISE EXCEPTION 'V300193 校验失败：主键缺失';
    END IF;

    -- 3.3 两个唯一约束（api_code、路由）
    SELECT count(*) INTO v_uk FROM pg_constraint c
      JOIN pg_class r ON r.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = r.relnamespace
     WHERE n.nspname = 'open' AND r.relname = 'open_api_endpoint'
       AND c.conname IN ('uk_open_api_endpoint_code','uk_open_api_endpoint_route');
    IF v_uk <> 2 THEN
        RAISE EXCEPTION 'V300193 校验失败：唯一约束应为 2 个，实际 %', v_uk;
    END IF;

    -- 3.4 五个 CHECK（code / method / path / 3 个 flag）
    SELECT count(*) INTO v_chk FROM pg_constraint c
      JOIN pg_class r ON r.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = r.relnamespace
     WHERE n.nspname = 'open' AND r.relname = 'open_api_endpoint'
       AND c.conname IN ('ck_open_api_endpoint_code','ck_open_api_endpoint_method',
                         'ck_open_api_endpoint_path','ck_open_api_endpoint_flag_write',
                         'ck_open_api_endpoint_flag_public','ck_open_api_endpoint_flag_enable');
    IF v_chk <> 6 THEN
        RAISE EXCEPTION 'V300193 校验失败：CHECK 约束应为 6 个，实际 %', v_chk;
    END IF;

    -- 3.5 gmt_update 触发器
    SELECT count(*) INTO v_trg FROM pg_trigger t
      JOIN pg_class r ON r.oid = t.tgrelid
      JOIN pg_namespace n ON n.oid = r.relnamespace
     WHERE n.nspname = 'open' AND r.relname = 'open_api_endpoint'
       AND t.tgname = 'trg_open_api_endpoint_set_gmt_update' AND NOT t.tgisinternal;
    IF v_trg <> 1 THEN
        RAISE EXCEPTION 'V300193 校验失败：gmt_update 触发器缺失';
    END IF;

    -- 3.6 种子可查到（本脚本自己写的 4 条编码）
    SELECT count(*) INTO v_seed FROM open.open_api_endpoint
     WHERE api_code IN ('cdeu.min.pageuni','cdeu.min.upsert',
                        'cdeu.realtime.stockupsert','auth.sts.issue');
    IF v_seed <> 4 THEN
        RAISE EXCEPTION 'V300193 校验失败：4 条种子接口应全部登记，实际只查到 %', v_seed;
    END IF;

    -- 3.7 数量提示（不阻断：代码可能条件注册接口）
    SELECT count(*) INTO v_rows FROM open.open_api_endpoint;
    RAISE NOTICE 'V300193 就绪：open_api_endpoint 共 % 行（代码当前注册 4 个可调接口，含 1 个条件注册）', v_rows;
    RAISE NOTICE 'V300193 提醒：本表是接口目录，不是鉴权白名单；允许调哪些接口仍由 router.go 的路由注册决定';
END $$;

COMMIT;
