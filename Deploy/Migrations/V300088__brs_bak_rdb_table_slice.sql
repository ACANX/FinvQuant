-- =====================================================================
-- V300088：BRS 大表增量（分片）备份登记表
--
-- 需求 10905：
--   · 新增 brs.brs_bak_rdb_table_slice：一行 = 一张需要按分片增量备份的大表；
--   · 与小表全量备份登记 brs.brs_bak_rdb_table 完全独立（不合并、不加列）；
--   · 首期种子：cdeu.finv_quote_secu_kline_min 按自然日 date 切分；
--   · 分片维度由 slice_mode + slice_key_sql + slice_where_tpl 表达，
--     新增「周 / 月 / 地域 / 自定义条件」只需加一行配置，不改代码。
--
-- 备份产物：
--   本地 <FINV_BRS_BACKUP_DIR>/Slice/<db>.<schema>.<table>/<分片键>.dump
--   远端 <prefix>/<env>/<db>.<schema>.<table>/<分片键>.dump
--   同一分片键重复备份覆盖上一次（不生成时间戳副本）。
-- =====================================================================

BEGIN;

CREATE TABLE IF NOT EXISTS brs.brs_bak_rdb_table_slice (
    idn             bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,          -- 主键
    rdb_type        varchar(32)  NOT NULL DEFAULT 'postgresql',                         -- 数据库类型（首期 postgresql）
    db              varchar(64)  NOT NULL DEFAULT 'finv',                               -- 归属库（产物文件名前缀）
    schema_name     varchar(64)  NOT NULL,                                              -- schema 名
    table_name      varchar(128) NOT NULL,                                              -- 表名
    flag_enable     char(1)      NOT NULL DEFAULT '1',                                  -- 启用开关：1 启用 / 0 停用
    priority        integer      NOT NULL DEFAULT 500,                                  -- 执行顺序，越大越先
    slice_mode      varchar(16)  NOT NULL DEFAULT 'date',                               -- 分片维度：date/week/month/column/expr
    slice_key_sql   text,                                                               -- 分片枚举 SQL（空则按 mode 取内置模板）
    slice_where_tpl text         NOT NULL DEFAULT 'date = {value}',                     -- where 模板，占位 {value}/{start}/{end}
    slice_file_tpl  varchar(128) NOT NULL DEFAULT '{key}',                              -- 产物文件名模板，占位 {key}
    bak_scope       varchar(16)  NOT NULL DEFAULT 'data',                               -- 备份范围：data/both/schema
    compression     varchar(16)  NOT NULL DEFAULT 'zstd',                               -- 压缩：none/gzip/zstd
    min_rows        bigint       NOT NULL DEFAULT 1000,                                 -- 行数低于该值的分片跳过
    max_slices      integer      NOT NULL DEFAULT 5000,                                 -- 分片数上限（防误配）
    redo_slices     integer      NOT NULL DEFAULT 2,                                     -- 末尾 N 个分片强制重做（当天可能在增长）
    flag_upload     char(1)      NOT NULL DEFAULT '1',                                  -- 上传开关：1 上传 / 0 仅本地
    remark          text,                                                               -- 备注
    creator         varchar(32),                                                        -- 创建人（sys_user.uid）
    gmt_create      timestamptz  NOT NULL DEFAULT now(),                                -- 创建时间
    gmt_update      timestamptz  NOT NULL DEFAULT now(),                                -- 修改时间（触发器维护）
    CONSTRAINT uq_brs_bak_rdb_table_slice UNIQUE (rdb_type, db, schema_name, table_name),
    CONSTRAINT ck_brs_bak_rdb_table_slice_flag CHECK (flag_enable IN ('0', '1')),
    CONSTRAINT ck_brs_bak_rdb_table_slice_upload CHECK (flag_upload IN ('0', '1')),
    CONSTRAINT ck_brs_bak_rdb_table_slice_mode CHECK (slice_mode IN ('date', 'week', 'month', 'column', 'expr')),
    CONSTRAINT ck_brs_bak_rdb_table_slice_scope CHECK (bak_scope IN ('both', 'data', 'schema')),
    CONSTRAINT ck_brs_bak_rdb_table_slice_compression CHECK (compression IN ('none', 'gzip', 'zstd')),
    CONSTRAINT ck_brs_bak_rdb_table_slice_limits CHECK (min_rows >= 0 AND max_slices > 0 AND redo_slices >= 0)
);

COMMENT ON TABLE brs.brs_bak_rdb_table_slice IS '大表增量（分片）备份登记：按分片维度切分导出，同一分片键覆盖（BRS）';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.idn IS '主键';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.rdb_type IS '数据库类型（首期 postgresql）';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.db IS '归属库，用作备份文件名前缀';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.schema_name IS 'schema 名';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.table_name IS '表名';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.flag_enable IS '启用开关：1 启用 / 0 停用';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.priority IS '执行顺序，越大越先';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.slice_mode IS '分片维度：date（自然日）/week（ISO 周）/month（自然月）/column（按列值）/expr（自定义 SQL）';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.slice_key_sql IS '分片枚举 SQL，须返回 4 列（key, start, end, rows）；为空时按 slice_mode 使用内置模板';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.slice_where_tpl IS 'pg_dump --where 模板，占位符 {value}/{start}/{end}；周月分片应写成区间条件以走索引';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.slice_file_tpl IS '产物文件名模板，占位符 {key}，默认 {key}';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.bak_scope IS '备份范围：data（默认，仅数据）/both/schema';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.compression IS '压缩：none/gzip/zstd';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.min_rows IS '分片行数下限，低于该值跳过（避免碎片文件）';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.max_slices IS '分片数上限，超过则拒绝执行（防误配）';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.redo_slices IS '末尾 N 个分片强制重做（最近的日期可能仍在增长）';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.flag_upload IS '上传开关：1 上传对象存储 / 0 仅保留本地';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.remark IS '备注';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.creator IS '创建人（sys_user.uid）';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.gmt_create IS '创建时间';
COMMENT ON COLUMN brs.brs_bak_rdb_table_slice.gmt_update IS '修改时间（触发器维护）';

-- gmt_update 触发器复用 V300060 已建函数 brs.brs_set_gmt_update()
DROP TRIGGER IF EXISTS trg_brs_bak_rdb_table_slice_gmt_update ON brs.brs_bak_rdb_table_slice;
CREATE TRIGGER trg_brs_bak_rdb_table_slice_gmt_update
    BEFORE UPDATE ON brs.brs_bak_rdb_table_slice
    FOR EACH ROW EXECUTE FUNCTION brs.brs_set_gmt_update();

-- 首期种子：行情分钟 K 线按自然日 date 切分（day 值为 yyyyMMdd 整数）
INSERT INTO brs.brs_bak_rdb_table_slice
    (rdb_type, db, schema_name, table_name, flag_enable, priority,
     slice_mode, slice_key_sql, slice_where_tpl, slice_file_tpl,
     bak_scope, compression, min_rows, max_slices, redo_slices, flag_upload, remark, creator)
VALUES
    ('postgresql', 'finv', 'cdeu', 'finv_quote_secu_kline_min', '1', 500,
     'date', NULL, 'date = {value}', '{key}',
     'data', 'zstd', 1000, 5000, 2, '1',
     '大表增量备份：按自然日 date 切分，每个日期一份、重跑覆盖（需求 10905）', 'migration')
ON CONFLICT ON CONSTRAINT uq_brs_bak_rdb_table_slice DO NOTHING;

COMMIT;
