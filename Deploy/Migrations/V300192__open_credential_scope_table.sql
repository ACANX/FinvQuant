-- =====================================================================
-- FinvQuant PostgreSQL V300192：open schema 新增 open.open_api_credential_scope（凭证授权范围明细）
--
-- 需求：11219（建表 + 从 scope_str 回填）。
-- 授权依据：用户在 2026-11-11 会话中明确要求「先建表，回填数据」。
--
-- 背景（当初的延后决议）：
--   V300183 头注释 ⑥ 与 Docs/DataDictMapping/OpenApiAuth.md 记录：授权范围先用
--   `open.open_api_credential.scope_str` 单列 jsonb，条目多到需要索引/分组再演进成本表。
--   本迁移只做**第一步**：建表 + 回填快照，**不改动任何读写代码**——
--   鉴权与页面仍以 `scope_str` 为准，本表当前是它的结构化镜像。
--
-- 三条语义（与鉴权侧 InScope 口径严格对齐）：
--   ① 某凭证在本表 **0 行 = 不限接口**（对应 scope_str 的 `[]`/空，语义是「全部放行」）；
--   ② `method = '*'` 表示任意方法（对应 jsonb 里 method 为空或 `*`），**不用 NULL**
--      —— PG 唯一索引里 NULL 互不相等，用 NULL 挡不住同一规则的重复插入；
--   ③ `path_pattern` 支持精确路径、尾部 `/*` 前缀匹配、尾部 `/` 目录匹配，与
--      `internal/api/openapi/credential.go` 的 `InScope` 完全一致。
--
-- 关键约束（不得随意放宽）：
--   - 全库 **0 物理外键**：`credential_idn` 只在程序层校验（DbSchemaSpec「跨域引用只走程序层」）；
--   - method 用 CHECK 收敛到 HTTP 白名单 + `*`，path 必须以 `/` 开头且长度 > 1；
--   - 回填只 `INSERT ... ON CONFLICT DO NOTHING`，不 DELETE、不 UPDATE——
--     【红线】迁移不得覆盖用户后来改过的值；
--   - 本轮**不删除** `scope_str` 列（删除属破坏性操作，需单独授权）；
--     因此两处数据可能漂移，接入读写前以 `scope_str` 为准，末尾 NOTICE 会对账提示差异。
--
-- 幂等：CREATE TABLE/INDEX IF NOT EXISTS、COMMENT 可重复、触发器先 DROP IF EXISTS 再建、
--   回填 ON CONFLICT DO NOTHING；重跑影响 0 行。
-- 迁移策略：单事务（BEGIN/COMMIT），失败整体回滚。
-- 收敛校验口径：只断言**本脚本自己刚写的结构**（表/列/约束/索引/触发器存在性与类型）；
--   条目数、坏数据、与 scope_str 的漂移一律 `RAISE NOTICE`，不阻断迁移。
-- 前置：schema open（V100013）、open.open_api_credential（V300183）、public.vq_set_gmt_update()（V200001）。
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 0. schema 兜底（V100013 已建；此处保证单独执行本文件也不失败）
-- ---------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS open AUTHORIZATION CURRENT_USER;

-- ---------------------------------------------------------------------
-- 1. 授权范围明细表：open.open_api_credential_scope
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS open.open_api_credential_scope (
    idn             BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    credential_idn  BIGINT       NOT NULL,
    method          VARCHAR(8)   NOT NULL DEFAULT '*',
    path_pattern    VARCHAR(256) NOT NULL,
    remark          VARCHAR(500) NULL,
    create_by       VARCHAR(32)  NULL,
    gmt_create      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    gmt_update      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_open_api_credential_scope PRIMARY KEY (idn),
    CONSTRAINT uk_open_api_credential_scope_rule
        UNIQUE (credential_idn, method, path_pattern),
    CONSTRAINT ck_open_api_credential_scope_method
        CHECK (method IN ('*','GET','POST','PUT','PATCH','DELETE','HEAD','OPTIONS')),
    CONSTRAINT ck_open_api_credential_scope_path
        CHECK (path_pattern LIKE '/%' AND length(path_pattern) > 1)
);

COMMENT ON TABLE  open.open_api_credential_scope IS
    '凭证授权范围明细：一行 = 一条「方法 + 路径」规则；某凭证 0 行 = 不限接口（全部放行）（需求 11219）';
COMMENT ON COLUMN open.open_api_credential_scope.idn IS '主键，自增';
COMMENT ON COLUMN open.open_api_credential_scope.credential_idn IS
    '所属凭证（对 open.open_api_credential.idn，程序层校验，无物理外键）';
COMMENT ON COLUMN open.open_api_credential_scope.method IS
    'HTTP 方法：GET/POST/PUT/PATCH/DELETE/HEAD/OPTIONS；* = 任意方法（等价 scope_str 里 method 为空或通配）';
COMMENT ON COLUMN open.open_api_credential_scope.path_pattern IS
    '路径规则：精确路径，或尾部 /* 前缀匹配，或尾部 / 目录匹配（与鉴权侧 InScope 口径一致）';
COMMENT ON COLUMN open.open_api_credential_scope.remark IS '备注（当前回填行标记来源，接入读写后用于规则级说明）';
COMMENT ON COLUMN open.open_api_credential_scope.create_by IS '创建人（回填行为 migrate）';
COMMENT ON COLUMN open.open_api_credential_scope.gmt_create IS '创建时间';
COMMENT ON COLUMN open.open_api_credential_scope.gmt_update IS
    '更新时间（触发器 trg_open_api_credential_scope_set_gmt_update 维护）';

-- 按凭证取全部规则（鉴权热路径与列表页）
CREATE INDEX IF NOT EXISTS idx_open_api_credential_scope_cred
    ON open.open_api_credential_scope (credential_idn);

-- 反查「谁有某个接口的权限」/ 出授权报表
CREATE INDEX IF NOT EXISTS idx_open_api_credential_scope_rule
    ON open.open_api_credential_scope (method, path_pattern);

DROP TRIGGER IF EXISTS trg_open_api_credential_scope_set_gmt_update ON open.open_api_credential_scope;
CREATE TRIGGER trg_open_api_credential_scope_set_gmt_update
    BEFORE UPDATE ON open.open_api_credential_scope
    FOR EACH ROW EXECUTE FUNCTION public.vq_set_gmt_update();

-- ---------------------------------------------------------------------
-- 2. 从 scope_str 回填
--
-- 只回填**能通过新表约束**的条目：
--   - scope_str 必须是数组、元素必须是对象、path 非空且以 `/` 开头、长度 > 1；
--   - method 归一为大写，空 → '*'，且必须落在 CHECK 白名单内。
-- 不符合的条目不回填（保持原样留给人工修），绝不"猜测"或放大成 `*`——
--   这与中间件「scope_str 损坏按拒绝处理」的口径一致（需求 11190）。
-- 同一凭证内重复的 (method, path) 去重；跨重跑靠 ON CONFLICT DO NOTHING 保持幂等。
-- ---------------------------------------------------------------------
CREATE TEMP TABLE tmp_scope_backfill ON COMMIT DROP AS
SELECT DISTINCT
       c.idn                                          AS credential_idn,
       COALESCE(NULLIF(btrim(upper(r->>'method')), ''), '*') AS method,
       btrim(r->>'path')                              AS path_pattern
  FROM open.open_api_credential c
  CROSS JOIN LATERAL jsonb_array_elements(c.scope_str) AS r
 WHERE jsonb_typeof(c.scope_str) = 'array'
   AND jsonb_typeof(r) = 'object'
   AND NULLIF(btrim(r->>'path'), '') IS NOT NULL
   AND btrim(r->>'path') LIKE '/%'
   AND length(btrim(r->>'path')) > 1
   AND COALESCE(NULLIF(btrim(upper(r->>'method')), ''), '*')
       IN ('*','GET','POST','PUT','PATCH','DELETE','HEAD','OPTIONS');

INSERT INTO open.open_api_credential_scope
    (credential_idn, method, path_pattern, create_by, remark)
SELECT credential_idn, method, path_pattern, 'migrate', 'V300192 从 scope_str 回填（需求 11219）'
  FROM tmp_scope_backfill
ON CONFLICT (credential_idn, method, path_pattern) DO NOTHING;

-- ---------------------------------------------------------------------
-- 3. 收敛校验（只断言结构性事实；数据质量与漂移只输出提示）
-- ---------------------------------------------------------------------
DO $$
DECLARE
    v_cols      INT;
    v_pk        INT;
    v_uk        INT;
    v_chk       INT;
    v_idx_cred  INT;
    v_idx_rule  INT;
    v_trg       INT;
    v_src_legal BIGINT;
    v_src_bad   BIGINT;
    v_table     BIGINT;
BEGIN
    -- 3.1 表与列
    SELECT count(*) INTO v_cols FROM information_schema.columns
     WHERE table_schema = 'open' AND table_name = 'open_api_credential_scope';
    IF v_cols <> 8 THEN
        RAISE EXCEPTION 'V300192 校验失败：open_api_credential_scope 列数应为 8，实际 %', v_cols;
    END IF;

    -- 3.2 主键 / 唯一 / CHECK
    SELECT count(*) INTO v_pk FROM pg_constraint c
      JOIN pg_class r ON r.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = r.relnamespace
     WHERE n.nspname = 'open' AND r.relname = 'open_api_credential_scope'
       AND c.contype = 'p';
    IF v_pk <> 1 THEN
        RAISE EXCEPTION 'V300192 校验失败：主键缺失';
    END IF;

    SELECT count(*) INTO v_uk FROM pg_constraint c
      JOIN pg_class r ON r.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = r.relnamespace
     WHERE n.nspname = 'open' AND r.relname = 'open_api_credential_scope'
       AND c.conname = 'uk_open_api_credential_scope_rule';
    IF v_uk = 0 THEN
        RAISE EXCEPTION 'V300192 校验失败：唯一约束 uk_open_api_credential_scope_rule 缺失';
    END IF;

    SELECT count(*) INTO v_chk FROM pg_constraint c
      JOIN pg_class r ON r.oid = c.conrelid
      JOIN pg_namespace n ON n.oid = r.relnamespace
     WHERE n.nspname = 'open' AND r.relname = 'open_api_credential_scope'
       AND c.conname IN ('ck_open_api_credential_scope_method','ck_open_api_credential_scope_path');
    IF v_chk <> 2 THEN
        RAISE EXCEPTION 'V300192 校验失败：CHECK 约束应为 2 个，实际 %', v_chk;
    END IF;

    -- 3.3 索引与触发器
    SELECT count(*) INTO v_idx_cred FROM pg_indexes
     WHERE schemaname = 'open' AND tablename = 'open_api_credential_scope'
       AND indexname = 'idx_open_api_credential_scope_cred';
    IF v_idx_cred <> 1 THEN
        RAISE EXCEPTION 'V300192 校验失败：索引 idx_open_api_credential_scope_cred 缺失';
    END IF;

    SELECT count(*) INTO v_idx_rule FROM pg_indexes
     WHERE schemaname = 'open' AND tablename = 'open_api_credential_scope'
       AND indexname = 'idx_open_api_credential_scope_rule';
    IF v_idx_rule <> 1 THEN
        RAISE EXCEPTION 'V300192 校验失败：索引 idx_open_api_credential_scope_rule 缺失';
    END IF;

    SELECT count(*) INTO v_trg FROM pg_trigger t
      JOIN pg_class r ON r.oid = t.tgrelid
      JOIN pg_namespace n ON n.oid = r.relnamespace
     WHERE n.nspname = 'open' AND r.relname = 'open_api_credential_scope'
       AND t.tgname = 'trg_open_api_credential_scope_set_gmt_update'
       AND NOT t.tgisinternal;
    IF v_trg <> 1 THEN
        RAISE EXCEPTION 'V300192 校验失败：gmt_update 触发器缺失';
    END IF;

    -- 3.4 数据对账（只提示，不阻断）
    SELECT count(*) INTO v_src_legal
      FROM open.open_api_credential c
      CROSS JOIN LATERAL jsonb_array_elements(c.scope_str) AS r
     WHERE jsonb_typeof(c.scope_str) = 'array'
       AND jsonb_typeof(r) = 'object'
       AND NULLIF(btrim(r->>'path'), '') IS NOT NULL
       AND btrim(r->>'path') LIKE '/%'
       AND length(btrim(r->>'path')) > 1
       AND COALESCE(NULLIF(btrim(upper(r->>'method')), ''), '*')
           IN ('*','GET','POST','PUT','PATCH','DELETE','HEAD','OPTIONS');

    SELECT count(*) INTO v_src_bad
      FROM open.open_api_credential c
      CROSS JOIN LATERAL jsonb_array_elements(c.scope_str) AS r
     WHERE jsonb_typeof(c.scope_str) = 'array'
       AND NOT (
              jsonb_typeof(r) = 'object'
          AND NULLIF(btrim(r->>'path'), '') IS NOT NULL
          AND btrim(r->>'path') LIKE '/%'
          AND length(btrim(r->>'path')) > 1
          AND COALESCE(NULLIF(btrim(upper(r->>'method')), ''), '*')
              IN ('*','GET','POST','PUT','PATCH','DELETE','HEAD','OPTIONS')
       );

    SELECT count(*) INTO v_table FROM open.open_api_credential_scope;

    IF v_src_bad > 0 THEN
        RAISE NOTICE 'V300192 提示：scope_str 中有 % 条不符合结构要求（非对象元素 / path 非法 / method 越界），未回填，请人工核对', v_src_bad;
    END IF;

    RAISE NOTICE 'V300192 就绪：open_api_credential_scope 共 % 行；scope_str 合法条目 % 条（去重后差异属正常）',
        v_table, v_src_legal;

    IF v_table < v_src_legal THEN
        RAISE NOTICE 'V300192 提示：表行数小于 scope_str 合法条目数，差额应为同凭证内重复规则去重所致；若不符请人工核对';
    END IF;

    RAISE NOTICE 'V300192 提醒：本表当前是 scope_str 的镜像快照，鉴权与页面仍读 scope_str；接入读写前两处可能漂移';
END $$;

COMMIT;
